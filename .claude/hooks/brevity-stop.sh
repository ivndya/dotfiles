#!/bin/sh
# Stop: если финальный ответ длинный, просит Claude ответить заново «в двух
# словах» — то, что пользователь раньше писал руками. Пересказ тоже
# проверяется: если он всё ещё длинный, просит сократить ещё раз (не больше
# MAX_TRIES блокировок за ход).
# Код в ```lang не считается; блоки без языка (черновики сообщений) считаются.
# Порог откалиброван по ответам, которые устраивали пользователя после его
# «в двух словах»: медиана ~170 символов, p75 ~270.
export LC_ALL=en_US.UTF-8
MAX_LINES=3
MAX_CHARS=300
MAX_TRIES=2

in=$(cat)
sid=$(printf '%s' "$in" | jq -r '.session_id // empty')
[ -n "$sid" ] || exit 0
active=$(printf '%s' "$in" | jq -r '.stop_hook_active // false')

dir="${TMPDIR:-/tmp}/claude-brevity"
[ -e "$dir/$sid.verbose" ] && exit 0
tries=$(cat "$dir/$sid.tries" 2>/dev/null || echo 0)
# Продолжение после чужого Stop-хука не трогаем; после своего — проверяем пересказ.
if [ "$active" = true ] && [ "$tries" -eq 0 ]; then exit 0; fi
[ "$tries" -ge "$MAX_TRIES" ] && exit 0

prose=$(printf '%s' "$in" | jq -r '.last_assistant_message // empty' \
  | awk '/^[[:space:]]*```/ {
           if (!f) { f = 1; code = ($0 ~ /```[[:space:]]*[A-Za-z]/) } else f = 0
           next
         }
         (!f || !code) && NF' \
  | sed -E 's/\]\([^)]*\)/]/g')
[ -n "$prose" ] || exit 0
lines=$(printf '%s\n' "$prose" | grep -c .)
chars=$(printf '%s' "$prose" | wc -m | tr -d ' ')

[ "$lines" -gt "$MAX_LINES" ] || [ "$chars" -gt "$MAX_CHARS" ] || exit 0

mkdir -p "$dir"
echo $((tries + 1)) > "$dir/$sid.tries"
if [ "$tries" -eq 0 ]; then
  r="Ответ длинный ($chars символов). Пользователь сейчас написал бы «в двух словах». Ответь заново так, будто он это написал: 1–2 коротких предложения, до 200 символов — главный вывод и, если нужно, один вопрос или следующий шаг. Не сжимай прошлый ответ целиком, а выбрось детали: пути, ссылки, хеши, второстепенные цифры, скобки, перечисления. Честный статус («не закоммичено», «тесты упали») оставь. Если в ответе черновик сообщения — сократи и его до 1–2 предложений. Пример: «FREE-352 готов и проверен тестами, но не закоммичен. Коммитить и открывать MR в dev?»"
else
  r="Всё ещё длинно ($chars символов, нужно до 200). Оставь одно предложение с главным выводом и, если нужно, короткий вопрос. Остальное убери."
fi
jq -nc --arg r "$r" '{decision: "block", reason: $r}'
