#!/bin/sh
# UserPromptSubmit: напоминает о краткости и помечает ход, где пользователь
# сам просит подробностей (или вызывает скилл) — такой ход brevity-stop.sh
# не сокращает. Заодно сбрасывает счётчик сокращений за ход.
# Ложные срабатывания отсечены: «развернуто на dev» (статус тикета),
# «разберись»; явная просьба о краткости перевешивает всё.
export LC_ALL=en_US.UTF-8
in=$(cat)
sid=$(printf '%s' "$in" | jq -r '.session_id // empty')
[ -n "$sid" ] || exit 0

dir="${TMPDIR:-/tmp}/claude-brevity"
mkdir -p "$dir"
rm -f "$dir/$sid.tries"

verbose=$(printf '%s' "$in" | jq -r '.prompt // ""
  | (test("двух словах|коротк|кратко|короче|простыми словами"; "i") | not)
    and test("^/|подробн|детальн|разв[её]рнут(?![а-яё]*\\s+(на|в)\\s)|объясни|разбери(?!сь)|полн(ый|ого) отч[её]т|перечисли|списком|таблиц"; "i")')

if [ "$verbose" = true ]; then
  touch "$dir/$sid.verbose"
else
  rm -f "$dir/$sid.verbose"
  echo 'Финальный ответ — как будто пользователь попросил «в двух словах»: 1–2 коротких предложения, до ~200 символов — главный вывод и, если нужно, следующий шаг или вопрос. Без списков, заголовков, путей и ссылок, пока их не попросят.'
fi
